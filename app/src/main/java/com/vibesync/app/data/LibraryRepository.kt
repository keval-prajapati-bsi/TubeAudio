package com.vibesync.app.data

import com.vibesync.app.data.db.AppDatabase
import com.vibesync.app.data.db.PlaylistEntity
import com.vibesync.app.data.db.PlaylistTrackDao
import com.vibesync.app.data.db.TrackEntity
import com.vibesync.app.extractor.ResolvedAudio
import com.vibesync.app.extractor.SearchResult
import kotlinx.coroutines.flow.Flow

const val DEFAULT_PLAYLIST_NAME = "All songs"

/** Sentinel "playlist id" for the Downloads tab's play queue -- there's no real playlist row
 *  for it, but [com.vibesync.app.data.db.PlaybackStateEntity.queuePlaylistId] has no foreign-key
 *  constraint, so this is safe to persist/restore against like a real one. Negative so it can
 *  never collide with a real autogenerated playlist id (which start at 1). */
const val DOWNLOADS_QUEUE_ID = -1L

/** Same idea as [DOWNLOADS_QUEUE_ID], for a single ad-hoc play (a search/trending result played
 *  directly, without being saved to the library first) -- since the track may not even exist in
 *  the `tracks` table yet, this queue is never persisted/resumed across app restarts, see
 *  [com.vibesync.app.ui.MainViewModel.playSearchResultDirectly]. */
const val ADHOC_QUEUE_ID = -2L

/** Same idea again, for the Liked Songs quick-access screen's own queue -- keeps shuffle/skip
 *  scoped to just your liked songs, same reasoning as [DOWNLOADS_QUEUE_ID]. */
const val LIKED_QUEUE_ID = -3L

/**
 * Higher-level operations over the track/playlist/cross-ref DAOs. The "Default"
 * playlist is created once on first use and holds every track ever added, newest
 * first; custom playlists are user-created and hold tracks in append order.
 */
class LibraryRepository(private val db: AppDatabase) {

    private val trackDao = db.trackDao()
    private val playlistDao = db.playlistDao()
    private val playlistTrackDao: PlaylistTrackDao = db.playlistTrackDao()

    val playlists: Flow<List<PlaylistEntity>> = playlistDao.observePlaylists()
    val recentPlaylists: Flow<List<PlaylistEntity>> = playlistDao.observeRecentPlaylists()
    val downloadedTracks: Flow<List<TrackEntity>> = trackDao.observeDownloaded()
    val likedTracks: Flow<List<TrackEntity>> = trackDao.observeLiked()

    suspend fun getDownloadedTracksOnce(): List<TrackEntity> = trackDao.getDownloadedOnce()

    /** Used by the Now Playing screen's heart/"Add to playlist" actions, which may be acting on
     *  a currently-playing track that was never saved (an ad-hoc direct play) -- saves it first
     *  (lands in "All songs", like every other save path) if it isn't in the library yet. */
    suspend fun ensureTrackSaved(track: TrackEntity): TrackEntity =
        trackDao.getByVideoId(track.videoId) ?: upsertAndPrependToDefault(track)

    /** Same idea as [toggleLikeFromSearchResult] but starting from a [TrackEntity] (the Now
     *  Playing screen's heart icon) rather than a [SearchResult]. */
    suspend fun toggleLikeTrack(track: TrackEntity) {
        val existing = trackDao.getByVideoId(track.videoId)
        if (existing != null) {
            trackDao.setLiked(track.videoId, !existing.isLiked)
        } else {
            upsertAndPrependToDefault(track.copy(isLiked = true))
        }
    }

    suspend fun getLikedTracksOnce(): List<TrackEntity> = trackDao.getLikedOnce()

    /** Toggles like state for a track already known to the library (e.g. from a playlist or
     *  the Downloads tab). */
    suspend fun toggleLike(videoId: String) {
        val existing = trackDao.getByVideoId(videoId) ?: return
        trackDao.setLiked(videoId, !existing.isLiked)
    }

    /** Toggles like for a search/trending result that may not be saved yet -- liking always
     *  saves it (lands in "All songs" like everything else does), since "Liked Songs" needs the
     *  track to actually exist in the library. */
    suspend fun toggleLikeFromSearchResult(result: SearchResult) {
        val existing = trackDao.getByVideoId(result.videoId)
        if (existing != null) {
            trackDao.setLiked(result.videoId, !existing.isLiked)
        } else {
            upsertAndPrependToDefault(
                TrackEntity(
                    videoId = result.videoId,
                    url = result.url,
                    title = result.title,
                    thumbnailUrl = result.thumbnailUrl,
                    durationSeconds = result.durationSeconds,
                    addedAtEpochMillis = System.currentTimeMillis(),
                    isLiked = true
                )
            )
        }
    }

    suspend fun ensureDefaultPlaylist(): PlaylistEntity {
        playlistDao.getDefaultPlaylist()?.let { return it }
        val id = playlistDao.insert(
            PlaylistEntity(name = DEFAULT_PLAYLIST_NAME, isDefault = true, createdAtEpochMillis = System.currentTimeMillis())
        )
        return playlistDao.getById(id)!!
    }

    /** Saves a resolved link as a track and puts it at the front of the Default playlist. */
    suspend fun addToDefault(resolved: ResolvedAudio): TrackEntity = upsertAndPrependToDefault(
        TrackEntity(
            videoId = resolved.videoId,
            url = resolved.canonicalUrl,
            title = resolved.title,
            thumbnailUrl = resolved.thumbnailUrl,
            durationSeconds = resolved.durationSeconds,
            addedAtEpochMillis = System.currentTimeMillis()
        )
    )

    /** Adds a song found via [com.vibesync.app.extractor.YouTubeSearcher] straight from its
     *  search-result metadata -- no stream resolve needed since we're only saving it, not
     *  playing it yet. */
    suspend fun addSearchResultToDefault(result: SearchResult): TrackEntity = upsertAndPrependToDefault(
        TrackEntity(
            videoId = result.videoId,
            url = result.url,
            title = result.title,
            thumbnailUrl = result.thumbnailUrl,
            durationSeconds = result.durationSeconds,
            addedAtEpochMillis = System.currentTimeMillis()
        )
    )

    private suspend fun upsertAndPrependToDefault(track: TrackEntity): TrackEntity {
        trackDao.upsert(track)
        val default = ensureDefaultPlaylist()
        playlistTrackDao.remove(default.id, track.videoId)
        playlistTrackDao.prependToDefault(default.id, track.videoId)
        return track
    }

    fun observeTracksForPlaylist(playlistId: Long): Flow<List<TrackEntity>> =
        playlistTrackDao.observeTracksForPlaylist(playlistId)

    fun observeTrackCount(playlistId: Long): Flow<Int> = playlistTrackDao.observeTrackCount(playlistId)

    fun observeCoverThumbnail(playlistId: Long): Flow<String?> = playlistTrackDao.observeCoverThumbnail(playlistId)

    suspend fun touchPlaylist(playlistId: Long) = playlistDao.touchLastPlayed(playlistId, System.currentTimeMillis())

    suspend fun getTracksForPlaylistOnce(playlistId: Long): List<TrackEntity> =
        playlistTrackDao.getTracksForPlaylistOnce(playlistId)

    suspend fun playlistIdsForTrack(videoId: String): List<Long> = playlistTrackDao.playlistIdsForTrack(videoId)

    fun searchTracks(query: String): Flow<List<TrackEntity>> = trackDao.search(query)

    suspend fun reorderPlaylist(playlistId: Long, orderedVideoIds: List<String>) =
        playlistTrackDao.reorder(playlistId, orderedVideoIds)

    suspend fun createPlaylist(
        name: String,
        description: String? = null,
        coverImageUri: String? = null,
        themeColorArgb: Int? = null
    ): PlaylistEntity {
        val id = playlistDao.insert(
            PlaylistEntity(
                name = name,
                isDefault = false,
                createdAtEpochMillis = System.currentTimeMillis(),
                description = description,
                coverImageUri = coverImageUri,
                themeColorArgb = themeColorArgb
            )
        )
        return playlistDao.getById(id)!!
    }

    suspend fun renamePlaylist(id: Long, name: String) = playlistDao.rename(id, name)

    suspend fun deletePlaylist(id: Long) = playlistDao.delete(id)

    suspend fun addTrackToPlaylist(playlistId: Long, videoId: String) =
        playlistTrackDao.appendToPlaylist(playlistId, videoId)

    suspend fun removeTrackFromPlaylist(playlistId: Long, videoId: String) =
        playlistTrackDao.remove(playlistId, videoId)

    /** Deletes a track everywhere (cascades out of every playlist, including Default). */
    suspend fun deleteTrack(videoId: String) = trackDao.delete(videoId)

    suspend fun getTrack(videoId: String): TrackEntity? = trackDao.getByVideoId(videoId)

    suspend fun markDownloaded(videoId: String, path: String) = trackDao.markDownloaded(videoId, path)

    suspend fun clearDownload(videoId: String) = trackDao.clearDownload(videoId)

    /** Recreates a playlist from an imported link list -- no network calls, since export/import
     *  only ever carries metadata + the original YouTube link, never a (short-lived) stream URL. */
    suspend fun importPlaylist(name: String, tracks: List<ImportedTrack>): PlaylistEntity {
        val playlist = createPlaylist(name)
        val defaultId = ensureDefaultPlaylist().id
        tracks.forEach { imported ->
            trackDao.upsert(
                TrackEntity(
                    videoId = imported.videoId,
                    url = imported.url,
                    title = imported.title,
                    thumbnailUrl = imported.thumbnailUrl,
                    durationSeconds = imported.durationSeconds,
                    addedAtEpochMillis = System.currentTimeMillis()
                )
            )
            playlistTrackDao.appendToPlaylist(defaultId, imported.videoId)
            playlistTrackDao.appendToPlaylist(playlist.id, imported.videoId)
        }
        return playlist
    }
}
